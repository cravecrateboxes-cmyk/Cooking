// Builds the installable home-screen version into webapp/: the normal Vite build plus a web app
// manifest, app icons, iOS full-screen tags and an offline service worker. Host webapp/ as static files.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const ROOT = path.resolve(import.meta.dirname, '..');
const DIST = path.join(ROOT, 'dist');
const OUT = path.join(ROOT, 'webapp');

fs.rmSync(OUT, { recursive: true, force: true });
fs.cpSync(DIST, OUT, { recursive: true });

const files = [];
const walk = (d) => {
  for (const f of fs.readdirSync(d)) {
    const p = path.join(d, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else files.push(path.relative(OUT, p).split(path.sep).join('/'));
  }
};
walk(OUT);

const manifest = {
  name: 'Order Up',
  short_name: 'Order Up',
  description: 'Cook it. Serve it. Grow it.',
  start_url: './',
  scope: './',
  display: 'fullscreen',
  display_override: ['fullscreen', 'standalone'],
  orientation: 'portrait',
  background_color: '#2b1640',
  theme_color: '#2b1640',
  icons: [
    { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png' },
    { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png' },
    { src: 'icons/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
};
fs.writeFileSync(path.join(OUT, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2));

// the cache name changes whenever any shipped file changes, so a new build replaces the old one
const precache = ['./', ...files.filter((f) => f !== 'index.html'), 'manifest.webmanifest'];
const hash = crypto.createHash('sha256');
for (const f of files) hash.update(f).update(fs.readFileSync(path.join(OUT, f)));
const version = hash.digest('hex').slice(0, 12);
fs.writeFileSync(
  path.join(OUT, 'sw.js'),
  `// Offline cache for Order Up (generated by scripts/webapp.mjs)
const CACHE = 'order-up-${version}';
const FILES = ${JSON.stringify(precache)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  // pages: network first so a new build shows up; everything else is fingerprinted, so cache first
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).catch(() => caches.match('./')));
    return;
  }
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
});
`,
);

const head = [
  '<link rel="manifest" href="./manifest.webmanifest" />',
  '<link rel="icon" type="image/png" sizes="192x192" href="./icons/icon-192.png" />',
  '<link rel="apple-touch-icon" href="./icons/icon-180.png" />',
  '<meta name="mobile-web-app-capable" content="yes" />',
  '<meta name="apple-mobile-web-app-capable" content="yes" />',
  '<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />',
  '<meta name="apple-mobile-web-app-title" content="Order Up" />',
].join('\n    ');
const reg = `<script>if ('serviceWorker' in navigator) addEventListener('load', () => navigator.serviceWorker.register('./sw.js').catch((e) => console.warn('offline cache unavailable', e)));</script>`;
let html = fs.readFileSync(path.join(OUT, 'index.html'), 'utf8');
html = html.replace('<meta name="theme-color" content="#ff8a2b" />', '<meta name="theme-color" content="#2b1640" />');
html = html.replace('</head>', `    ${head}\n    ${reg}\n  </head>`);
fs.writeFileSync(path.join(OUT, 'index.html'), html);
fs.writeFileSync(path.join(OUT, '.nojekyll'), '');
console.warn(`webapp/ ready: ${files.length} files, cache ${version}`);
